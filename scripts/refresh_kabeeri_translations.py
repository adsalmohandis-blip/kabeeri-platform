def php_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def php_array(value, indent: int = 0) -> str:
    space = " " * indent
    inner = " " * (indent + 4)

    if isinstance(value, dict):
        lines = ["["]
        for key, item in value.items():
            lines.append(f"{inner}{php_string(str(key))} => {php_array(item, indent + 4)},")
        lines.append(f"{space}]")
        return "\n".join(lines)

    if isinstance(value, list):
        lines = ["["]
        for item in value:
            lines.append(f"{inner}{php_array(item, indent + 4)},")
        lines.append(f"{space}]")
        return "\n".join(lines)

    if isinstance(value, bool):
        return "true" if value else "false"

    if value is None:
        return "null"

    return php_string(str(value))


